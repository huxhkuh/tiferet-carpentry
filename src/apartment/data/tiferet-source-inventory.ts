/** Working planner models, including models that still require architectural audit. */
export function getImplementedApartmentSourcePlans(inventory: TiferetSourceInventory): TiferetSourcePlan[] {
  return inventory.apartmentPlans.filter((plan) => plan.modelStatus === 'partially-modeled');
}

export function getSourceInventorySummary(inventory: TiferetSourceInventory): TiferetSourceInventorySummary {
  const techeletApartmentPlans = inventory.apartmentPlans.filter((plan) => plan.buildingId === 'techelet').length;
  const argamanApartmentPlans = inventory.apartmentPlans.filter((plan) => plan.buildingId === 'argaman').length;
  const totalSourcePdfs =
    techeletApartmentPlans +
    argamanApartmentPlans +
    inventory.techeletFloorSheetCount +
    inventory.argamanFloorSheetCount +
    inventory.groundAndGardenPlanCount;

  return {
    techeletApartmentPlans,
    argamanApartmentPlans,
    techeletFloorSheets: inventory.techeletFloorSheetCount,
    argamanFloorSheets: inventory.argamanFloorSheetCount,
    groundAndGardenPlans: inventory.groundAndGardenPlanCount,
    totalSourcePdfs,
  };
}
